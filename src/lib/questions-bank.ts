export const QUESTIONS_BANK: BankQuestion[] = RAW_QUESTIONS.map((q) => ({
  ...q,
  options: q.options.map(capitalizeOption),
}));

export function getBankQuestionById(id: string): BankQuestion | undefined {
  return QUESTIONS_BANK.find((q) => q.id === id);
}

/** Публичный lookup картинки без отдачи correct_index в API */
export function getQuestionImageById(id: string): string | undefined {
  return QUESTIONS_BANK.find((q) => q.id === id)?.image;
}

export type QuestionImageAlign = "center" | "top" | "bottom";

/** Выравнивание object-position по номеру вопроса (из пути /questions/N.ext) */
const IMAGE_ALIGN_BY_NUMBER: Partial<Record<number, QuestionImageAlign>> = {
  14: "top",
  15: "bottom",
  28: "top",
  38: "top",
  45: "top",
  47: "top",
};

export function getQuestionNumberFromImage(image: string): number | null {
  const match = image.match(/\/questions\/(\d+)\./);
  if (!match) return null;
  return Number(match[1]);
}

export function getQuestionImageAlign(
  imageOrId: string
): QuestionImageAlign {
  const fromPath = getQuestionNumberFromImage(imageOrId);
  if (fromPath != null) {
    return IMAGE_ALIGN_BY_NUMBER[fromPath] ?? "center";
  }
  const q = getBankQuestionById(imageOrId);
  if (!q) return "center";
  const n = getQuestionNumberFromImage(q.image);
  return n != null ? IMAGE_ALIGN_BY_NUMBER[n] ?? "center" : "center";
}

export function getQuestionImageAlignClass(align: QuestionImageAlign): string {
  if (align === "top") return "quiz-question-panel__media--align-top";
  if (align === "bottom") return "quiz-question-panel__media--align-bottom";
  return "quiz-question-panel__media--align-center";
}

